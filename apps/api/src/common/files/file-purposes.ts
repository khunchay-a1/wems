/** Upload purposes, allowed extensions and size limits (M01 §5, docs/06-security.md §6). */
export const FILE_PURPOSES = {
  DOCUMENT_REVISION: {
    extensions: [
      'pdf',
      'dwg',
      'dxf',
      'rvt',
      'ifc',
      'xlsx',
      'xls',
      'docx',
      'doc',
      'pptx',
      'csv',
      'zip',
    ],
    maxBytes: 1024 ** 3,
  },
  ATTACHMENT: {
    extensions: ['jpg', 'jpeg', 'png', 'heic', 'pdf', 'xlsx', 'docx'],
    maxBytes: 50 * 1024 ** 2,
  },
  PHOTO: { extensions: ['jpg', 'jpeg', 'png', 'heic'], maxBytes: 20 * 1024 ** 2 },
  IMPORT: { extensions: ['xlsx', 'csv'], maxBytes: 10 * 1024 ** 2 },
  SIGNATURE_IMAGE: { extensions: ['png'], maxBytes: 2 * 1024 ** 2 },
  LICENSE_SCAN: { extensions: ['pdf', 'jpg', 'png'], maxBytes: 10 * 1024 ** 2 },
  CLIENT_RESPONSE: { extensions: ['pdf', 'jpg', 'png', 'docx', 'xlsx'], maxBytes: 50 * 1024 ** 2 },
  /** Generated by the system (transmittal cover sheets, CRS, ZIP packages) — never uploaded by users */
  SYSTEM_GENERATED: { extensions: ['pdf', 'zip', 'xlsx', 'png'], maxBytes: 5 * 1024 ** 3 },
} as const;

export type FilePurpose = keyof typeof FILE_PURPOSES;
export const USER_UPLOAD_PURPOSES = Object.keys(FILE_PURPOSES).filter(
  (p) => p !== 'SYSTEM_GENERATED',
) as Exclude<FilePurpose, 'SYSTEM_GENERATED'>[];

export function extensionOf(name: string): string {
  const m = /\.([A-Za-z0-9]{1,10})$/.exec(name.trim());
  return m ? m[1]!.toLowerCase() : '';
}

/** Storage key {env}/{yyyy}/{mm}/{fileId}/{sanitizedName} — never the raw user name (docs/02-architecture.md §7). */
export function storageKey(env: string, now: Date, fileId: string, originalName: string): string {
  const yyyy = now.getUTCFullYear();
  const mm = String(now.getUTCMonth() + 1).padStart(2, '0');
  return `${env}/${yyyy}/${mm}/${fileId}/${sanitizeFileName(originalName)}`;
}

export function sanitizeFileName(name: string): string {
  const ext = extensionOf(name);
  const base = name
    .normalize('NFC')
    .replace(/\.[^.]*$/, '')
    .replace(/[^\p{L}\p{M}\p{N}._-]+/gu, '_')
    .replace(/_+/g, '_')
    .replace(/^[_.]+|[_.]+$/g, '')
    .slice(0, 120);
  return `${base || 'file'}${ext ? `.${ext}` : ''}`;
}

/** RFC 6266/5987 Content-Disposition with a UTF-8 file name (Thai names survive). */
export function contentDisposition(name: string, inline: boolean): string {
  const ascii = name.replace(/[^\x20-\x7e]+/g, '_').replace(/["\\]/g, '_');
  return `${inline ? 'inline' : 'attachment'}; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(name)}`;
}

/** PDFs and images open inline; everything else downloads (prevents HTML/SVG XSS — docs/06-security.md §6). */
export function isInlineType(mime: string): boolean {
  return mime === 'application/pdf' || ['image/png', 'image/jpeg'].includes(mime);
}
