/** Minimal RFC 4180 CSV parser (quoted fields, escaped quotes, commas/newlines in quotes). */
export function parseCsv<K extends string = string>(text: string): Record<K, string>[] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;
  const src = text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (inQuotes) {
      if (c === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else inQuotes = false;
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && src[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      if (row.some((v) => v !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) {
    row.push(field);
    if (row.some((v) => v !== '')) rows.push(row);
  }
  const [header, ...data] = rows;
  if (!header) return [];
  return data.map(
    (r) =>
      Object.fromEntries(header.map((h, idx) => [h.trim(), (r[idx] ?? '').trim()])) as Record<
        K,
        string
      >,
  );
}
